// Assembles the release package for the CURRENT working tree and writes MANIFEST.json + SHA256SUMS.
//   ESBUILD=$PWD/node_modules/.bin/esbuild node scripts/package-release.mjs [--lab /path/to/lab] [--out release]
// Run AFTER `scripts/build.mjs`. It rebuilds the Match Lab runner + worker from the same sources, also syncs them into the Lab working copy,
// generates SAMPLE (unpaired) coach files, and records full fingerprints. Nothing here contains a provider key or a real pairing capability.
import { execFileSync, execSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const root = process.cwd();
const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i >= 0 ? process.argv[i + 1] : d; };
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const out = join(root, arg('out', 'release'), `Bloodboard-${pkg.version}`);
const labSrc = arg('lab', process.env.LAB_DIR || '/home/claude/w/lab');
const esbuild = process.env.ESBUILD || join(root, 'node_modules/.bin/esbuild');
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true });

// 1. Match Lab runner + worker from the current sources
const banner = "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);";
const buildRunner = (dir) => {
  mkdirSync(join(dir, 'source'), { recursive: true });
  execFileSync(esbuild, ['scripts/match-lab-runner.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', `--banner:js=${banner}`, `--outfile=${join(dir, 'runner.mjs')}`, '--log-level=warning'], { stdio: 'inherit' });
  execFileSync(esbuild, ['src/platform/engine-worker.ts', '--bundle', '--format=iife', '--target=es2020', `--outfile=${join(dir, 'engine-worker.js')}`, '--log-level=warning'], { stdio: 'inherit' });
  cpSync('src', join(dir, 'source', 'src'), { recursive: true }); cpSync('scripts/match-lab-runner.ts', join(dir, 'source', 'match-lab-runner.ts'));
};
if (!existsSync(join(labSrc, 'lab.mjs'))) throw new Error(`Match Lab folder not found: ${labSrc} (use --lab)`);
cpSync(labSrc, join(out, 'match-lab'), { recursive: true, filter: (s) => !/[\\/](runs|history|queue|logs)([\\/]|$)/.test(s) });
// the ONE AI-folder resolver is shipped byte-identically in the game package (online/) and the Lab
cpSync(join(root, 'online', 'aidir.mjs'), join(out, 'match-lab', 'aidir.mjs'));
if (process.argv.includes('--sync-lab')) cpSync(join(root, 'online', 'aidir.mjs'), join(labSrc, 'aidir.mjs'));
buildRunner(join(out, 'match-lab', 'runner'));
if (process.argv.includes('--sync-lab')) buildRunner(join(labSrc, 'runner'));

// 2. Web app, online bridge (no node_modules), docs, native sources, build scripts
cpSync('dist/web', join(out, 'web'), { recursive: true });
cpSync('online', join(out, 'online'), { recursive: true, filter: (s) => !/node_modules|verification-reports/.test(s) });
cpSync('docs', join(out, 'docs'), { recursive: true, filter: (s) => !/\.zh-CN\./.test(s) }); // English-only package
cpSync('native', join(out, 'native'), { recursive: true });
cpSync('lan', join(out, 'lan'), { recursive: true, filter: (s) => !/[\\/]rooms([\\/]|$)/.test(s) });
for (const f of ['INSTALL.md', 'install_bloodboard.sh', 'retire_obsolete.sh', 'build_mac_app.sh', 'PROGRESS.json', 'NEXT_SESSION.md', 'ROADMAP.md', 'package.json']) cpSync(f, join(out, f));

// 3. SAMPLE coach files (unpaired all-zero capability: loadable, but cannot reach any bridge until regenerated by the panel / install-coach)
mkdirSync(join(out, 'coaches-sample'), { recursive: true });
const { coachSource } = await import(join(root, 'online', 'build-coach.mjs'));
for (const provider of ['deepseek', 'luna']) {
  const { config, text } = await coachSource({ provider, model: 'sample', capability: '0'.repeat(64) });
  writeFileSync(join(out, 'coaches-sample', `Online-${provider === 'luna' ? 'ChatGPT Luna' : 'DeepSeek'}-SAMPLE-UNPAIRED-${config.version}.js`), text);
}

// 4. Manifest + checksums
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]);
const files = walk(out).filter((f) => !/SHA256SUMS|MANIFEST\.json/.test(f)).sort();
const fp = JSON.parse(readFileSync('PROGRESS.json', 'utf8')).fingerprint;
const bi = JSON.parse(readFileSync('dist/web/build-info.json', 'utf8'));
const BUILD_FINGERPRINT = JSON.parse(/BUILD_FINGERPRINT = (\{[\s\S]*?\}) as const/.exec(readFileSync('src/engine/fingerprint.ts', 'utf8'))[1]);
const manifest = {
  product: 'Bloodboard', version: pkg.version, builtAt: new Date().toISOString(),
  fingerprints: BUILD_FINGERPRINT, previousProgressJsonFingerprint: fp, webBuild: bi,
  lab: { runner: sha(join(out, 'match-lab/runner/runner.mjs')), worker: sha(join(out, 'match-lab/runner/engine-worker.js')) },
  testedSourceSha256: existsSync('/tmp/alpha2/tested-source.sha256') ? readFileSync('/tmp/alpha2/tested-source.sha256', 'utf8').split(' ')[0] : null,
  packagedSourceSha256: execSync("tar --sort=name --mtime=@0 --owner=0 --group=0 --exclude=node_modules --exclude=verification-reports --exclude=lan/engine.mjs --exclude=lan/rooms -cf - src tests scripts package.json tsconfig.json native online lan build_mac_app.sh | sha256sum", { cwd: root, shell: '/bin/bash' }).toString().split(' ')[0],
  nativeMacBuild: 'NOT BUILT: the cloud cannot compile Swift. native/*.swift are unverified until built and launched on a Mac.',
  aiFolderPolicy: { module: 'online/aidir.mjs', sha256: sha(join(out, 'online/aidir.mjs')), labCopySha256: sha(join(out, 'match-lab/aidir.mjs')), canonical: '~/Library/Application Support/Bloodboard/AI' },
  files: files.length,
};
if (manifest.aiFolderPolicy.sha256 !== manifest.aiFolderPolicy.labCopySha256) throw new Error('online/aidir.mjs and match-lab/aidir.mjs differ');
writeFileSync(join(out, 'MANIFEST.json'), JSON.stringify(manifest, null, 2));
const sums = files.concat(join(out, 'MANIFEST.json')).map((f) => `${sha(f)}  ${relative(out, f)}`).join('\n') + '\n';
writeFileSync(join(out, 'SHA256SUMS'), sums);
console.log(`package: ${out}\n${files.length} files; runner ${manifest.lab.runner.slice(0, 12)} worker ${manifest.lab.worker.slice(0, 12)}`);
