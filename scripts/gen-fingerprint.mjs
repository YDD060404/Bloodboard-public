// Generates src/engine/fingerprint.ts: SHA-256 fingerprints of what this build actually contains.
//   engineHash: every src/engine/*.ts (rules, legality, state transitions, dice)
//   rulesHash : the rule DATA and rule code that decide outcomes (engine files without UI-facing helpers is not separable, so = engineHash over rules files)
//   apiHash   : the AI protocol (src/platform/*.ts and src/platform/v2/*.ts, docs/schemas/platform/*.json)
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const hashDir = (dir, re, skip = []) => {
  const h = createHash('sha256');
  const walk = (d) => { for (const n of readdirSync(d).sort()) { const p = join(d, n); if (statSync(p).isDirectory()) { if (n !== 'research') walk(p); } else if (re.test(n) && !skip.includes(n)) { h.update(n + '\0'); h.update(readFileSync(p)); } } };
  if (existsSync(dir)) walk(dir);
  return h.digest('hex');
};
const rulesSkip = ['replay.ts', 'fingerprint.ts', 'serialize.ts', 'legal.ts', 'sim.ts', 'receipts.ts'];
const engineHash = hashDir(join(root, 'src/engine'), /\.(ts|json)$/, ['fingerprint.ts']);
const rulesHash = hashDir(join(root, 'src/engine'), /\.(ts|json)$/, rulesSkip);
const apiHash = createHash('sha256').update(hashDir(join(root, 'src/platform'), /\.ts$/, ['hostext.ts'])).update(hashDir(join(root, 'docs/schemas/platform'), /\.json$/)).digest('hex');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const out = `// GENERATED by scripts/gen-fingerprint.mjs — do not edit. Fingerprints of the sources this build contains.
export const BUILD_FINGERPRINT = ${JSON.stringify({ version: pkg.version, engineHash, rulesHash, apiHash, saveFormatVersion: 2, aiApiVersion: '2.0' }, null, 2)} as const;
`;
writeFileSync(join(root, 'src/engine/fingerprint.ts'), out);
console.log('fingerprint', engineHash.slice(0, 12), rulesHash.slice(0, 12), apiHash.slice(0, 12));
