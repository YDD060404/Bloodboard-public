// Build script: generates example positions, bundles the rules engine, the
// interface and the CLI with esbuild, and assembles dist/web (the app's web
// resources used by the native Mac wrapper and by the browser fallback).
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, rmSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const esbuild = process.env.ESBUILD || 'esbuild';
const run = (args) => execFileSync(esbuild, args, { cwd: root, stdio: 'inherit' });

const dist = join(root, 'dist');
const web = join(dist, 'web');
rmSync(dist, { recursive: true, force: true });
mkdirSync(web, { recursive: true });
mkdirSync(join(root, 'build'), { recursive: true });

// 0) V6: fingerprints of the sources being bundled (engine / rules / AI protocol)
execFileSync(process.execPath, [join(root, 'scripts/gen-fingerprint.mjs')], { stdio: 'inherit' });

// 1) examples
run(['scripts/make-examples.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', '--outfile=build/make-examples.mjs', '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);
execFileSync(process.execPath, [join(root, 'build/make-examples.mjs'), join(root, 'examples')], { stdio: 'inherit' });

// 2) engine (standalone global for the interface)
run(['src/engine/index.ts', '--bundle', '--format=iife', '--global-name=BloodboardEngine', '--target=es2020', `--outfile=${join(web, 'engine.js')}`, '--log-level=warning']);
// 2b) V5.7 engine worker: the engine plus the analysis services, bundled as one script. The pool's workers run it (Web Workers in the
// app, worker_threads headless). The app embeds it as text (engine-worker-src.js) so a Blob worker can start without any file fetch.
run(['src/platform/engine-worker.ts', '--bundle', '--format=iife', '--target=es2020', `--outfile=${join(web, 'engine-worker.js')}`, '--log-level=warning']);
writeFileSync(join(web, 'engine-worker-src.js'), `// Generated by scripts/build.mjs: the engine worker script as text (Blob workers).\nwindow.BLOODBOARD_ENGINE_WORKER_SRC = ${JSON.stringify(readFileSync(join(web, 'engine-worker.js'), 'utf8'))};\n`);
// 3) interface
run(['src/ui/main.ts', '--bundle', '--format=iife', '--target=es2020', `--outfile=${join(web, 'app.js')}`, '--log-level=warning']);
// 4) static files
cpSync(join(root, 'src/ui/index.html'), join(web, 'index.html'));
cpSync(join(root, 'src/ui/styles.css'), join(web, 'app.css'));
// V5.5: the AI files — ai/*.json|js are the bundled AI files (the Mac app puts them into its AI folder once; the
// browser reads them from ai/bundled.js), ai/examples/ the examples (copied into the AI folder's Examples).
cpSync(join(root, 'ai'), join(web, 'ai'), { recursive: true });
{
  const files = readdirSync(join(root, 'ai')).filter((n) => /\.(json|js)$/i.test(n)).sort();
  const list = files.map((name) => ({ name, text: readFileSync(join(root, 'ai', name), 'utf8') }));
  writeFileSync(join(web, 'ai', 'bundled.js'), `// Generated by scripts/build.mjs: the AI files bundled with this page (browser use).\nwindow.BLOODBOARD_BUNDLED_AI = ${JSON.stringify(list)};\n`);
}
// 5) CLI (headless interface boundary)
mkdirSync(join(dist, 'cli'), { recursive: true });
run(['cli/bloodboard-cli.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', `--outfile=${join(dist, 'cli/bloodboard-cli.mjs')}`, '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);

// 5b) The authoritative engine for the LAN / internet match server (Node ESM, generated; lan/engine.mjs is not hand-edited)
mkdirSync(join(root, 'lan'), { recursive: true });
run(['src/platform/lan-engine.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', `--outfile=${join(root, 'lan/engine.mjs')}`, '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);

// 6) docs/EXAMPLES.md (walkthroughs computed by the engine)
run(['scripts/make-example-docs.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', '--outfile=build/make-example-docs.mjs', '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);
execFileSync(process.execPath, [join(root, 'build/make-example-docs.mjs'), root], { stdio: 'inherit' });

run(['scripts/make-rules-doc.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', '--outfile=build/make-rules-doc.mjs', '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);
execFileSync(process.execPath, [join(root, 'build/make-rules-doc.mjs'), root], { stdio: 'inherit' });

// docs/BLOCK_SCHOOL.md (course coverage and workbook differences, computed by the engine)
run(['scripts/make-block-school-doc.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', '--outfile=build/make-block-school-doc.mjs', '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);
execFileSync(process.execPath, [join(root, 'build/make-block-school-doc.mjs'), root], { stdio: 'inherit' });

// docs/BLOCK_DICE_AUDIT.md (reproducible samples; about 10 s). Skip with BLOODBOARD_SKIP_AUDIT=1.
if (!process.env.BLOODBOARD_SKIP_AUDIT) {
  run(['scripts/audit-block-dice.ts', '--bundle', '--platform=node', '--format=esm', '--target=node18', '--outfile=build/audit-block-dice.mjs', '--log-level=warning', "--banner:js=import { createRequire } from 'module'; const require = createRequire(import.meta.url);"]);
  execFileSync(process.execPath, [join(root, 'build/audit-block-dice.mjs'), root], { stdio: 'inherit' });
}

// 7) JSON Schemas of the interface formats (needs the typescript package; optional)
try {
  execFileSync(process.execPath, [join(root, 'scripts/make-schemas.mjs')], { stdio: 'inherit' });
} catch {
  console.warn('Skipped docs/schemas (install the typescript dev dependency to regenerate them).');
}

execFileSync(process.execPath, [join(root, 'scripts/gen-api-v2-docs.mjs')], { stdio: 'inherit' });

const size = (f) => (readFileSync(f).length / 1024).toFixed(0) + ' KB';
console.log(`dist/web/engine.js ${size(join(web, 'engine.js'))}, dist/web/app.js ${size(join(web, 'app.js'))}, dist/web/engine-worker.js ${size(join(web, 'engine-worker.js'))}`);
{
  // V5.8: what this bundle is — checked by the game's end-to-end test and by anyone comparing a served page with the source.
  const { createHash } = await import('node:crypto');
  const sha = (f) => createHash('sha256').update(readFileSync(join(web, f))).digest('hex');
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  writeFileSync(join(web, 'build-info.json'), JSON.stringify({ version: pkg.version, hostExtensions: { version: '1.0', setup: true, coachContext: true }, builtAt: new Date().toISOString(), sha256: { 'app.js': sha('app.js'), 'engine.js': sha('engine.js'), 'engine-worker.js': sha('engine-worker.js'), 'index.html': sha('index.html') } }, null, 1));
}
if (!existsSync(join(web, 'index.html'))) process.exit(1);
