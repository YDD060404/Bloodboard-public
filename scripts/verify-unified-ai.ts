import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import * as Engine from '../src/engine/index';
import {bindEngine,type CoachEntry} from '../src/ai/index';
import {moduleMeta,platformDecide} from '../src/platform/host';
import {nodeSpawn} from '../src/platform/research/nodehost';
import {observeV2} from '../src/platform/v2obs';
import {Pos,c} from '../tests/helpers';
bindEngine(Engine);
const path='ai/hopeful-2-5-s4-37u-c-unified.js';
const code=readFileSync(path,'utf8');const m=await moduleMeta(nodeSpawn,code);assert.ok(m.meta,m.error);
const metadata=m.meta!;
const entry={...metadata,apiGeneration:metadata.apiVersion,code,kind:'strategy',implementation:'strategy:'+metadata.id} as unknown as CoachEntry;
const b=new Pos({rerollsA:1,rerollsB:1,turnA:2,turnB:1});
const carrier=b.add('A','human','thrower',c(10,7),{id:'A1'});
b.add('A','human','lineman',c(8,6),{id:'A2'});
b.add('B','orc','lineman',c(12,7),{id:'B1'});
b.add('B','orc','lineman',c(22,7),{id:'B2'});b.give(carrier);
const state=b.start();state.rulesEdition='faq2026';
const before=JSON.stringify(state),observation=observeV2(state,'A',1);
assert.deepEqual(observation.engine,{version:Engine.BUILD_FINGERPRINT.version,engineHash:Engine.BUILD_FINGERPRINT.engineHash,rulesHash:Engine.BUILD_FINGERPRINT.rulesHash,apiHash:Engine.BUILD_FINGERPRINT.apiHash});
const t=Date.now();const result=await platformDecide(state,'A',entry,{spawn:nodeSpawn});
assert.equal(result.meta.fellBack,false,result.meta.reason ?? undefined);assert.equal(result.move?.type,'action');
const input=(result.move as any).input;assert.deepEqual(Engine.validateInput(state,input),[]);
assert.equal(JSON.stringify(state),before,'advice leaves source position unchanged');
writeFileSync('verification/unified-ai-real-raw.json',JSON.stringify(result,null,2)+'\n');
const trace=result.meta.trace as any;console.log('trace summary',JSON.stringify({keys:Object.keys(trace ?? {}),admission:trace?.learnedAdmission,truncated:trace?.truncated,bytes:trace?.bytes}));const domain=trace.learnedAdmission?.domain ?? trace.tacticalLearning?.learning_domain;
assert.equal(domain?.admitted,true,JSON.stringify(domain) ?? 'teacher admission missing from trace');
assert.equal(domain.runtimeEngine ?? domain.runtime_engine,'0.2.0');
writeFileSync('verification/unified-ai-real-engine.json',JSON.stringify({version:'0.2.0',elapsedMs:Date.now()-t,observation:observation.engine,rulesEdition:(observation as any).ruleset.rulesEdition,input,meta:result.meta,scope:'One sparse four-player real engine decision, legal/admitted/no fallback; not strength evidence'},null,2)+'\n');
console.log('UNIFIED AI REAL ENGINE PASS',Date.now()-t,input.kind);
