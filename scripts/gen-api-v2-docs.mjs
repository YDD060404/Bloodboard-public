// Generates docs/schemas/bloodboard-api-v2.schema.json and docs/AI_API_V2_TYPES.d.ts from src/platform/schemas-v2.ts (the single source).
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const esbuild = process.env.ESBUILD || join(root, 'node_modules/.bin/esbuild');
const out = join(root, 'build/schemas-v2.mjs');
execFileSync(esbuild, [join(root, 'src/platform/schemas-v2.ts'), '--bundle', '--platform=node', '--format=esm', `--outfile=${out}`, '--log-level=warning'], { stdio: 'inherit' });
const { V2_SCHEMAS } = await import(pathToFileURL(out).href);
const cap = (n) => n[0].toUpperCase() + n.slice(1);
function ts(s, ind = '') {
  if (!s || typeof s !== 'object') return 'unknown';
  if (s.anyOf) return s.anyOf.map((x) => ts(x, ind)).join(' | ');
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((x) => JSON.stringify(x)).join(' | ');
  if (s.type === 'integer' || s.type === 'number') return 'number';
  if (s.type === 'string' || s.type === 'boolean' || s.type === 'null') return s.type;
  if (s.type === 'array') return `Array<${ts(s.items, ind)}>`;
  if (s.type === 'object') {
    const props = s.properties || {};
    const keys = Object.keys(props);
    if (!keys.length) return 'Record<string, unknown>';
    const req = new Set(s.required || []);
    return `{\n${keys.map((k) => `${ind}  ${k}${req.has(k) ? '' : '?'}: ${ts(props[k], ind + '  ')};`).join('\n')}\n${ind}}`;
  }
  return 'unknown';
}
const schema = { $schema: 'https://json-schema.org/draft/2020-12/schema', $id: 'bloodboard-api-v2', title: 'Bloodboard AI API v2 contracts', definitions: V2_SCHEMAS };
mkdirSync(join(root, 'docs/schemas'), { recursive: true });
writeFileSync(join(root, 'docs/schemas/bloodboard-api-v2.schema.json'), JSON.stringify(schema, null, 1) + '\n');
const dts = ['// GENERATED by scripts/gen-api-v2-docs.mjs from src/platform/schemas-v2.ts — do not edit.', '// Types of the Bloodboard AI API v2 payloads (observation, choices, targets, forks, receipts, lifecycle requests).', '', ...Object.entries(V2_SCHEMAS).map(([n, s]) => `export type ${cap(n)} = ${ts(s)};\n`)].join('\n');
writeFileSync(join(root, 'docs/AI_API_V2_TYPES.d.ts'), dts);
console.log(`docs/schemas/bloodboard-api-v2.schema.json + docs/AI_API_V2_TYPES.d.ts (${Object.keys(V2_SCHEMAS).length} contracts)`);
